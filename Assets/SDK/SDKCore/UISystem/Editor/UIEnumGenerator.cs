using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace LSDK.UISystem.EditorTools
{
    public static class UIEnumGenerator
    {
        public static string GetPath(UIRegistry r) =>
            Path.Combine(UIRegistry.EnumOutputFolder, Sanitize(r.enumName) + ".cs").Replace('\\', '/');

        public static string Build(UIRegistry r)
        {
            var sb = new StringBuilder();
            var used = new HashSet<string> { "None" };
            bool hasNs = !string.IsNullOrWhiteSpace(r.enumNamespace);
            string ind = hasNs ? "    " : "";

            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// Generated by LSDK UI System (UIRegistry). Do not edit manually.");
            sb.AppendLine("// </auto-generated>");
            if (hasNs)
            {
                sb.AppendLine($"namespace {r.enumNamespace.Trim()}");
                sb.AppendLine("{");
            }
            sb.AppendLine($"{ind}public enum {Sanitize(r.enumName)}");
            sb.AppendLine($"{ind}{{");
            sb.AppendLine($"{ind}    None = 0,");
            foreach (var e in r.entries)
            {
                if (e == null || e.prefab == null) continue;
                sb.AppendLine($"{ind}    {Unique(Sanitize(e.name), used)} = {e.id},");
            }
            sb.AppendLine($"{ind}}}");
            if (hasNs) sb.AppendLine("}");
            return sb.ToString();
        }

        public static bool IsUpToDate(UIRegistry r)
        {
            string path = GetPath(r);
            return File.Exists(path) && Normalize(File.ReadAllText(path)) == Normalize(Build(r));
        }

        public static void Generate(UIRegistry r)
        {
            if (r == null) return;
            if (r.outputFolder != UIRegistry.EnumOutputFolder)
            {
                r.outputFolder = UIRegistry.EnumOutputFolder;
                EditorUtility.SetDirty(r);
            }

            string path = GetPath(r);
            if (!path.StartsWith("Assets/"))
            {
                Debug.LogError("[UI] Output folder must be inside Assets/ (packages are read-only).");
                return;
            }

            // đổi enumName/folder -> xoá file cũ để khỏi trùng type
            if (!string.IsNullOrEmpty(r.generatedPath) && r.generatedPath != path && File.Exists(r.generatedPath))
                AssetDatabase.DeleteAsset(r.generatedPath);

            string code = Build(r);
            if (!File.Exists(path) || Normalize(File.ReadAllText(path)) != Normalize(code))
            {
                Directory.CreateDirectory(Path.GetDirectoryName(path));
                File.WriteAllText(path, code, new UTF8Encoding(false));
                AssetDatabase.ImportAsset(path, ImportAssetOptions.ForceUpdate);
            }

            if (r.generatedPath != path)
            {
                r.generatedPath = path;
                EditorUtility.SetDirty(r);
            }
        }

        public static string Sanitize(string raw)
        {
            if (string.IsNullOrWhiteSpace(raw)) return "_";
            var sb = new StringBuilder();
            foreach (char c in raw.Trim())
                sb.Append(c < 128 && char.IsLetterOrDigit(c) ? c : '_');
            if (char.IsDigit(sb[0])) sb.Insert(0, '_');
            sb[0] = char.ToUpperInvariant(sb[0]);   // viết hoa -> không đụng keyword C#
            return sb.ToString();
        }

        static string Unique(string name, HashSet<string> used)
        {
            string result = name;
            int i = 2;
            while (!used.Add(result)) result = name + i++;
            return result;
        }

        static string Normalize(string s) => s.Replace("\r\n", "\n");
    }
}
