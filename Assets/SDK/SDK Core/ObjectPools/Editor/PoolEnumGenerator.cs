using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace LSDK.Core.ObjectPools.EditorTools
{
    public static class PoolEnumGenerator
    {
        public static string GetPath(PoolDatabaseSO db) =>
            Path.Combine(db.outputFolder, Sanitize(db.enumName) + ".cs").Replace('\\', '/');

        public static string Build(PoolDatabaseSO db)
        {
            var sb = new StringBuilder();
            var used = new HashSet<string> { "None" };
            bool hasNs = !string.IsNullOrWhiteSpace(db.enumNamespace);
            string ind = hasNs ? "    " : "";

            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// Generated by LSDK Object Pools (PoolDatabase). Do not edit manually.");
            sb.AppendLine("// </auto-generated>");
            if (hasNs)
            {
                sb.AppendLine($"namespace {db.enumNamespace.Trim()}");
                sb.AppendLine("{");
            }
            sb.AppendLine($"{ind}public enum {Sanitize(db.enumName)}");
            sb.AppendLine($"{ind}{{");
            sb.AppendLine($"{ind}    None = 0,");
            foreach (var e in db.entries)
            {
                if (e == null || e.prefab == null || e.id <= 0) continue;
                sb.AppendLine($"{ind}    {Unique(Sanitize(e.name), used)} = {e.id},");
            }
            sb.AppendLine($"{ind}}}");
            if (hasNs) sb.AppendLine("}");
            return sb.ToString();
        }

        public static bool IsUpToDate(PoolDatabaseSO db)
        {
            string path = GetPath(db);
            return File.Exists(path) && Normalize(File.ReadAllText(path)) == Normalize(Build(db));
        }

        public static void Generate(PoolDatabaseSO db)
        {
            if (db == null) return;
            string path = GetPath(db);
            if (!path.StartsWith("Assets/"))
            {
                Debug.LogError("[Pool] Output folder must be inside Assets/ (packages are read-only).");
                return;
            }

            if (!string.IsNullOrEmpty(db.generatedPath) && db.generatedPath != path && File.Exists(db.generatedPath))
                AssetDatabase.DeleteAsset(db.generatedPath);

            string code = Build(db);
            if (!File.Exists(path) || Normalize(File.ReadAllText(path)) != Normalize(code))
            {
                Directory.CreateDirectory(Path.GetDirectoryName(path));
                File.WriteAllText(path, code, new UTF8Encoding(false));
                AssetDatabase.ImportAsset(path, ImportAssetOptions.ForceUpdate);
            }

            if (db.generatedPath != path)
            {
                db.generatedPath = path;
                EditorUtility.SetDirty(db);
            }
        }

        public static string Sanitize(string raw)
        {
            if (string.IsNullOrWhiteSpace(raw)) return "_";
            var sb = new StringBuilder();
            foreach (char c in raw.Trim())
                sb.Append(c < 128 && char.IsLetterOrDigit(c) ? c : '_');
            if (char.IsDigit(sb[0])) sb.Insert(0, '_');
            sb[0] = char.ToUpperInvariant(sb[0]);
            return sb.ToString();
        }

        static string Unique(string name, HashSet<string> used)
        {
            string result = name;
            int i = 2;
            while (!used.Add(result)) result = name + i++;
            return result;
        }

        static string Normalize(string s) => s.Replace("\r\n", "\n");
    }
}
